#!/usr/bin/env node
/*
 * Extract translatable strings from src/*.ts into locales/messages.pot.
 *
 * Recognized calls: _('...'), N_('...') (single or double quoted literals).
 *
 * Usage:
 *   node scripts/extract-pot.js          # (re)write locales/messages.pot
 *   node scripts/extract-pot.js --check  # verify every locales/*.po covers all msgids
 */
const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const srcDir = path.join(rootDir, 'src');
const localesDir = path.join(rootDir, 'locales');
const potPath = path.join(localesDir, 'messages.pot');

function unescapeJs(s) {
	return s.replace(/\\(.)/g, (_m, c) => ({ n: '\n', t: '\t', r: '\r' }[c] || c));
}

function escapePo(s) {
	return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\t/g, '\\t');
}

function extract() {
	const messages = new Map(); // msgid -> [refs]
	const re = /\bN?_\(\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")/g;
	const files = fs.readdirSync(srcDir).filter(f => /\.tsx?$/.test(f) && !f.endsWith('.d.ts') && f !== 'i18n.ts').sort();
	for (const file of files) {
		const lines = fs.readFileSync(path.join(srcDir, file), 'utf8').split(/\r?\n/);
		lines.forEach((line, i) => {
			let m;
			re.lastIndex = 0;
			while ((m = re.exec(line)) !== null) {
				const msgid = unescapeJs(m[1] !== undefined ? m[1] : m[2]);
				if (!messages.has(msgid)) messages.set(msgid, []);
				messages.get(msgid).push(`src/${file}:${i + 1}`);
			}
		});
	}
	return messages;
}

function writePot(messages) {
	const out = [
		'# Translation template for the Joplin plugin "Favorites 2 (i18n test)".',
		'# This file is generated by scripts/extract-pot.js - do not edit by hand.',
		'#',
		'msgid ""',
		'msgstr ""',
		'"Project-Id-Version: joplin-plugin-akiratamcat-favorites-i18n\\n"',
		'"MIME-Version: 1.0\\n"',
		'"Content-Type: text/plain; charset=UTF-8\\n"',
		'"Content-Transfer-Encoding: 8bit\\n"',
		'',
	];
	for (const [msgid, refs] of messages) {
		out.push(`#: ${refs.join(' ')}`);
		if (msgid.includes('%s')) out.push('#, c-format');
		out.push(`msgid "${escapePo(msgid)}"`, 'msgstr ""', '');
	}
	fs.mkdirSync(localesDir, { recursive: true });
	fs.writeFileSync(potPath, out.join('\n'), 'utf8');
	console.info(`Wrote ${messages.size} messages to ${path.relative(rootDir, potPath)}`);
}

// Minimal PO reader (msgid -> msgstr), mirrors src/i18n.ts parsePo.
function readPo(file) {
	const entries = new Map();
	let entry = {}; let field = null;
	const flush = () => { if (entry.msgid) entries.set(entry.msgid, entry.msgstr || ''); entry = {}; field = null; };
	for (const raw of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
		const line = raw.trim();
		if (!line) { flush(); continue; }
		if (line.startsWith('#')) continue;
		const m = line.match(/^(msgctxt|msgid|msgstr)\s+"(.*)"$/);
		if (m) {
			if (m[1] === 'msgid' && entry.msgstr !== undefined) flush();
			field = m[1]; entry[field] = unescapeJs(m[2]); continue;
		}
		const c = line.match(/^"(.*)"$/);
		if (c && field) entry[field] += unescapeJs(c[1]);
	}
	flush();
	return entries;
}

function check(messages) {
	let ok = true;
	const poFiles = fs.readdirSync(localesDir).filter(f => f.endsWith('.po')).sort();
	for (const f of poFiles) {
		const po = readPo(path.join(localesDir, f));
		const missing = [...messages.keys()].filter(id => !po.get(id));
		const extra = [...po.keys()].filter(id => !messages.has(id));
		const badFormat = [...messages.keys()].filter(id => po.get(id) &&
			(id.match(/%s/g) || []).length !== (po.get(id).match(/%s/g) || []).length);
		const status = (missing.length || extra.length || badFormat.length) ? 'NG' : 'OK';
		if (status === 'NG') ok = false;
		console.info(`${status} ${f}: ${po.size} entries, missing ${missing.length}, obsolete ${extra.length}, %s-mismatch ${badFormat.length}`);
		for (const id of missing) console.info(`   missing: ${JSON.stringify(id)}`);
		for (const id of extra) console.info(`   obsolete: ${JSON.stringify(id)}`);
		for (const id of badFormat) console.info(`   %s mismatch: ${JSON.stringify(id)}`);
	}
	if (!ok) process.exit(1);
}

const messages = extract();
if (process.argv.includes('--check')) check(messages);
else writePot(messages);
